#include <stdio.h>

int main(void) {
    int i , z , o , p;
    int arr[3];
    scanf("%d %d %d" , &arr[0] , &arr[1] , &arr[2]);
    for(p = 0 ; p < 2 ; p++){
        for(i = 0 ; i < 2 ; i++){
        if(arr[i] > arr[i+1]){
            z = arr[i];
            arr[i] = arr[i+1];
            arr[i+1] = z;
        }
        
    }
    }
    
    for(o = 0 ; o < 3 ; o++){
            printf("%d" , arr[o]);
            if(o < 2) printf("->");
        }
    return 0;
}

/*
 * ============================================================
 * 如何改成自适应 n 个数的通用版本？
 * ============================================================
 *
 * 当前代码中写死了 3 个数，所有出现数字 2 和 3 的地方都需要
 * 改成用变量 n 来表达。核心改动点如下：
 *
 * ────────────────────────────────────────────────────────────
 * 改动 1：数组大小不能写死
 * ────────────────────────────────────────────────────────────
 *   int arr[3];   →   int arr[100];  // 预估一个最大容量
 *   或者用宏定义：   #define MAXN 100
 *                  int arr[MAXN];
 *
 *   为什么不能 int arr[n]？
 *   因为 C 语言中，普通数组的大小必须在编译时确定。
 *   如果 n 是运行时才输入的，int arr[n] 属于「变长数组(VLA)」，
 *   不是所有编译器都支持，且不安全。建议用固定大小或动态分配。
 *
 * ────────────────────────────────────────────────────────────
 * 改动 2：先读入 n，再循环读入 n 个数
 * ────────────────────────────────────────────────────────────
 *   int n;
 *   scanf("%d", &n);               // 先读入个数
 *   for(i = 0; i < n; i++)         // 循环读入 n 个数
 *       scanf("%d", &arr[i]);
 *
 * ────────────────────────────────────────────────────────────
 * 改动 3：排序的循环边界用 n 来表达
 * ────────────────────────────────────────────────────────────
 *   外层（趟数）：n-1 趟
 *     for(p = 0; p < n-1; p++)
 *
 *   内层（每趟比较）：每趟比较 n-1-p 次
 *     for(i = 0; i < n-1-p; i++)
 *       if(arr[i] > arr[i+1])  交换;
 *
 *   为什么内层是 n-1-p？
 *   每做完一趟，最大的 p 个数已经沉到最后，无需再比较。
 *   这是冒泡排序的优化，不加优化写成 i < n-1 也可以。
 *
 * ────────────────────────────────────────────────────────────
 * 改动 4：输出的循环边界也改成 n
 * ────────────────────────────────────────────────────────────
 *   for(o = 0; o < n; o++){
 *       printf("%d", arr[o]);
 *       if(o < n-1) printf("->");  // 最后一个后面不加 ->
 *   }
 *
 * ────────────────────────────────────────────────────────────
 * 总结：当前代码和通用版本的对应关系
 * ────────────────────────────────────────────────────────────
 *   当前（3个数）          →     通用（n个数）
 *   int arr[3]            →     int arr[MAXN]
 *   scanf 写死 3 个 %d    →     for循环 scanf n 次
 *   p < 2                 →     p < n-1
 *   i < 2                 →     i < n-1-p
 *   o < 3                 →     o < n
 *   o < 2                 →     o < n-1
 *
 * ────────────────────────────────────────────────────────────
 * 和 Python 的对比
 * ────────────────────────────────────────────────────────────
 * Python:
 *   nums = list(map(int, input().split()))
 *   nums.sort()
 *   print("->".join(map(str, nums)))
 *
 * Python 的 list 自动扩容，sort() 一行搞定，join() 处理分隔符。
 * C 语言中每一件事都要手动做，但你能看到每一步的原理。
 */