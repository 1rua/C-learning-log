#include <stdio.h>
#include <math.h>
int main(void){
    int r , l , n , arr[6][6] , s1=0 , s2=0 , s=0;
    scanf("%d" , &n);
    for(r = 0 ; r < n ; r++){
        for(l = 0 ; l < n ; l++){
            scanf("%d" , &arr[r][l]);
        }
    }   
    for(r = l = 0 ; r < n && l < n ; r++ , l++){
        s1 = s1 + arr[r][l];
        }
    for(r = l = n ; r > 0 && l > 0 ; r-- , l--){
        s2 = s2 + arr[r][l];
        }
    s = s + (s1 + s2);
    if(n % 2 == 1){
        s = s - arr[n/2 + 1][n/2 + 1];
    }
    printf("%d" , s);

    return 0;
}
