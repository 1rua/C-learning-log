#include <stdio.h>
int main(){
    int i , n , fib[47];
    fib[0] = fib[1] = 1;
    scanf("%d" , &n);
    if(n >= 1){
        for(i = 2 ; i < n ; i++){
            fib[i] = fib[i - 2] + fib[i - 1];
        }
        for(i = 0 ; i < n ; i++){
            printf("%11d" , fib[i]);
            if((i+1) % 5 == 0){
                printf("\n");
            }
        }
        if(n % 5 != 0){
            printf("\n");
        }
    }
    else{
        printf("Invalid.");
    }
    return 0;
}

